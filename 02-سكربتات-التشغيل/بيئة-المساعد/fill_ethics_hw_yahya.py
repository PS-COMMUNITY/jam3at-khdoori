doc = Document(SRC)

def find_para(text_start):
    for p in doc.paragraphs:
        t = p.text.strip()
        if t.startswith(text_start):
            return p
    return None

def make_para_after(qp, text):
    """نسخ خصائص فقرة السؤال (اتجاه/خط) مع حذف أي ترقيم تلقائي"""
    new_p = copy.deepcopy(qp._p)
    for r in new_p.findall(qn('w:r')):
        new_p.remove(r)
    pPr = new_p.find(qn('w:pPr'))
    if pPr is not None:
        numPr = pPr.find(qn('w:numPr'))
        if numPr is not None:
            pPr.remove(numPr)
    r_src = None
    for r in qp._p.findall(qn('w:r')):
        rPr = r.find(qn('w:rPr'))
        if rPr is not None:
            r_src = copy.deepcopy(rPr)
            break
    r_new = OxmlElement('w:r')
    if r_src is not None:
        r_new.append(r_src)
    t = OxmlElement('w:t')
    t.set(qn('xml:space'), 'preserve')
    t.text = text
    r_new.append(t)
    new_p.append(r_new)
    qp._p.addnext(new_p)
    return new_p

# 1) تعبئة اسم الطالب (الفقرة تجمع سطر المدرس واسم الطالب بأسطر متعددة)
name_p = None
for p in doc.paragraphs:
    if 'اسم الطالب' in p.text:
        name_p = p
        break
if name_p is not None:
    r_new = OxmlElement('w:r')
    rPr_src = None
    for r in name_p._p.findall(qn('w:r')):
        rPr = r.find(qn('w:rPr'))
        if rPr is not None:
            rPr_src = copy.deepcopy(rPr)
            break
    if rPr_src is not None:
        r_new.append(rPr_src)
    t = OxmlElement('w:t')
    t.set(qn('xml:space'), 'preserve')
    t.text = ' ' + STUDENT_NAME
    r_new.append(t)
    name_p._p.append(r_new)
    print('OK: اسم الطالب ->', STUDENT_NAME)
else:
    print('!! فقرة اسم الطالب غير موجودة')

# 2) حقن الإجابات
count = 0
for q, paras in ANSWERS.items():
    qp = find_para(q)
    if qp is None:
        for p in doc.paragraphs:
            if q in p.text:
                qp = p
                break
    if qp is None:
        print('!! لم أجد السؤال:', q)
        continue
    for txt in reversed(paras):
        make_para_after(qp, txt)
    count += 1
    print('OK:', q[:40])

