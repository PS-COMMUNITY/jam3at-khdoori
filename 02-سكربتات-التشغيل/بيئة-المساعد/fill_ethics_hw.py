doc = Document(SRC)

def find_para(text_start):
    for p in doc.paragraphs:
        t = p.text.strip()
        if t.startswith(text_start):
            return p
    return None

def make_para_after(qp, text):
    """نسخ خصائص فقرة السؤال (اتجاه/خط) مع حذف أي ترقيم تلقائي"""
    from docx.oxml.ns import qn
    import re as _re
    new_p = copy.deepcopy(qp._p)
    # مسح كل الـ runs
    for r in new_p.findall(qn('w:r')):
        new_p.remove(r)
    # حذف الترقيم التلقائي إن وجد
    pPr = new_p.find(qn('w:pPr'))
    if pPr is not None:
        numPr = pPr.find(qn('w:numPr'))
        if numPr is not None:
            pPr.remove(numPr)
    # بناء run جديد بخاصية خط السؤال
    r_src = None
    for r in qp._p.findall(qn('w:r')):
        rPr = r.find(qn('w:rPr'))
        if rPr is not None:
            r_src = copy.deepcopy(rPr)
            break
    from docx.oxml import OxmlElement
    r_new = OxmlElement('w:r')
    if r_src is not None:
        r_new.append(r_src)
    t = OxmlElement('w:t')
    t.set(qn('xml:space'), 'preserve')
    t.text = text
    r_new.append(t)
    new_p.append(r_new)
    qp._p.addnext(new_p)
    return new_p

