doc = Document(SRC)

def find_para(text_start):
    for p in doc.paragraphs:
        t = p.text.strip()
        if t.startswith(text_start):
            return p
    return None

def first_rPr(p):
    for r in p._p.findall(qn('w:r')):
        rPr = r.find(qn('w:rPr'))
        if rPr is not None:
            return copy.deepcopy(rPr)
    return None

def _prep_rPr(rPr, bold):
    if rPr is None:
        return None
    rPr = copy.deepcopy(rPr)
    if not bold:
        for tag in ('w:b', 'w:bCs'):
            el = rPr.find(qn(tag))
            if el is not None:
                rPr.remove(el)
    return rPr

def insert_after(base_el, text, rPr_src, bold):
    """فقرة جديدة بعد base_el بنفس خصائص الفقرة الأساسية مع حذف الترقيم التلقائي"""
    new_p = copy.deepcopy(base_el)
    for child in list(new_p):
        if child.tag != qn('w:pPr'):
            new_p.remove(child)
    pPr = new_p.find(qn('w:pPr'))
    if pPr is not None:
        numPr = pPr.find(qn('w:numPr'))
        if numPr is not None:
            pPr.remove(numPr)
    r_new = OxmlElement('w:r')
    rPr = _prep_rPr(rPr_src, bold)
    if rPr is not None:
        r_new.append(rPr)
    t = OxmlElement('w:t')
    t.set(qn('xml:space'), 'preserve')
    t.text = text
    r_new.append(t)
    new_p.append(r_new)
    base_el.addnext(new_p)
    return new_p

def inject_block(qp, items):
    """حقن قائمة (نوع، نص) بعد فقرة السؤال؛ يعيد آخر عنصر في ترتيب DOM
    (العنصر المُدرج أولاً في الحقن العكسي هو items[-1] وهو الأخير في DOM)"""
    rPr_src = first_rPr(qp)
    first_inserted = None
    # الحقن بترتيب عكسي لأن addnext يضع العنصر مباشرة بعد الأساس
    for kind, txt in reversed(items):
        el = insert_after(qp._p, txt, rPr_src, bold=(kind == 'h'))
        if first_inserted is None:
            first_inserted = el
    return first_inserted

